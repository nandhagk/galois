(** * Equality generated by fact-guarded rules

    The relation closes guarded rule instances under equivalence and application congruence.
    For example, a related pair of children gives related applications of the same operator.
    Builds on: EgraphSyntax and EgraphRules. *)

From Stdlib Require Import List.
From Galois.Egraph Require Import EgraphSyntax EgraphRules.

Scheme All for Forall2.

Module EggEqual.

(** Rule instances carry facts valid for the terms substituted into their declared holes. *)
Inductive rel {K Sort V H F C} (a : EggAlg.t K Sort V)
    (adm : EggSem.t K V C -> Prop) (facts : EggFact.t F K Sort V C)
    (rules : list (EggRule.t K Sort V H F)) : EggTerm.t K Sort V -> EggTerm.t K Sort V -> Prop :=
  | refl : forall term, rel a adm facts rules term term
  | sym : forall l r, rel a adm facts rules l r -> rel a adm facts rules r l
  | trans : forall l m r,
      rel a adm facts rules l m -> rel a adm facts rules m r -> rel a adm facts rules l r
  | app : forall s op ls rs,
      Forall2 (rel a adm facts rules) ls rs ->
      rel a adm facts rules (EggTerm.App s op ls) (EggTerm.App s op rs)
  | rule : forall r sub phi l u,
      In r rules -> EggSubst.sub_typed a (EggRule.hole_sort r) sub ->
      (forall h term, In h (EggRule.holes r) -> EggSubst.get sub h = Some term ->
        EggFact.valid facts adm (phi h) term) ->
      EggRule.guard r phi = true ->
      EggSubst.instantiate sub (EggRule.lhs r) = Some l ->
      EggSubst.instantiate sub (EggRule.rhs r) = Some u -> rel a adm facts rules l u.

Local Lemma rel_ind_all {K Sort V H F C} (a : EggAlg.t K Sort V)
    (adm : EggSem.t K V C -> Prop) (facts : EggFact.t F K Sort V C)
    (rules : list (EggRule.t K Sort V H F)) (P : EggTerm.t K Sort V -> EggTerm.t K Sort V -> Prop)
    (Hrefl : forall term, P term term)
    (Hsym : forall l r, rel a adm facts rules l r -> P l r -> P r l)
    (Htrans : forall l m r, rel a adm facts rules l m -> P l m ->
      rel a adm facts rules m r -> P m r -> P l r)
    (Happ : forall s op ls rs, Forall2 (rel a adm facts rules) ls rs ->
      Forall2 P ls rs -> P (EggTerm.App s op ls) (EggTerm.App s op rs))
    (Hrule : forall r sub phi l u, In r rules ->
      EggSubst.sub_typed a (EggRule.hole_sort r) sub ->
      (forall h term, In h (EggRule.holes r) -> EggSubst.get sub h = Some term ->
        EggFact.valid facts adm (phi h) term) ->
      EggRule.guard r phi = true ->
      EggSubst.instantiate sub (EggRule.lhs r) = Some l ->
      EggSubst.instantiate sub (EggRule.rhs r) = Some u -> P l u) :
  forall l r, rel a adm facts rules l r -> P l r.
Proof.
  fix IH 3.
  intros l r Hequal.
  destruct Hequal as [term|l r Hequal|l m r Hlm Hmr|s op ls rs Hargs|
    rule sub phi l u Hin Hsub Hfacts Hguard Hlhs Hrhs].
  - exact (Hrefl term).
  - exact (Hsym l r Hequal (IH l r Hequal)).
  - exact (Htrans l m r Hlm (IH l m Hlm) Hmr (IH m r Hmr)).
  - apply Happ; [exact Hargs|].
    induction Hargs as [|l r ls rs Hlr Hrest IHrest].
    + constructor.
    + constructor; [exact (IH l r Hlr)|exact IHrest].
  - exact (Hrule rule sub phi l u Hin Hsub Hfacts Hguard Hlhs Hrhs).
Qed.

Local Lemma denote_args_cons {K Sort V C} (sem : EggSem.t K V C)
    (term : EggTerm.t K Sort V) terms :
  EggSem.denote_args sem (term :: terms) =
    match EggSem.denote sem term with
    | None => None
    | Some c => option_map (cons c) (EggSem.denote_args sem terms)
    end.
Proof.
  reflexivity.
Qed.

Local Lemma denote_app {K Sort V C} (sem : EggSem.t K V C) (s : Sort) op args :
  EggSem.denote sem (EggTerm.App s op args) =
    match EggSem.denote_args sem args with
    | None => None
    | Some cs => EggSem.eval_op sem op cs
    end.
Proof.
  reflexivity.
Qed.

Local Lemma denote_args_agrees {K Sort V C} (sem : EggSem.t K V C)
    (ls rs : list (EggTerm.t K Sort V)) :
  Forall2 (fun l r => EggSem.denote sem l = EggSem.denote sem r) ls rs ->
  EggSem.denote_args sem ls = EggSem.denote_args sem rs.
Proof.
  intros Hargs.
  induction Hargs as [|l r ls rs Hlr Hrest IHrest].
  - reflexivity.
  - rewrite !denote_args_cons.
    now rewrite Hlr, IHrest.
Qed.

(** Sound rules generate equality of partial results in every admissible interpretation. *)
Theorem sound {K Sort V H F C} (a : EggAlg.t K Sort V)
    (adm : EggSem.t K V C -> Prop) (facts : EggFact.t F K Sort V C)
    (rules : list (EggRule.t K Sort V H F)) :
  Forall (EggRule.sound a adm facts) rules ->
  forall l r, rel a adm facts rules l r -> EggSem.equiv adm l r.
Proof.
  intros Hrules.
  apply (rel_ind_all a adm facts rules (EggSem.equiv adm)).
  - intros term sem Hsem; reflexivity.
  - intros l r Hequal IH sem Hsem; symmetry; exact (IH sem Hsem).
  - intros l m r Hlm IHlm Hmr IHmr sem Hsem.
    transitivity (EggSem.denote sem m); [exact (IHlm sem Hsem)|exact (IHmr sem Hsem)].
  - intros s op ls rs Hargs IHargs sem Hsem.
    rewrite !denote_app.
    assert (Hdenotes : Forall2 (fun l r => EggSem.denote sem l = EggSem.denote sem r) ls rs).
    { clear Hargs.
      induction IHargs as [|l r ls rs Hlr Hrest IHrest].
      - constructor.
      - constructor; [exact (Hlr sem Hsem)|exact IHrest]. }
    now rewrite (denote_args_agrees sem ls rs Hdenotes).
  - intros rule sub phi l u Hin Hsub Hfacts Hguard Hlhs Hrhs.
    pose proof (proj1 (Forall_forall (EggRule.sound a adm facts) rules) Hrules rule Hin)
      as Hsound.
    exact (Hsound sub phi l u Hsub Hfacts Hguard Hlhs Hrhs).
Qed.

Local Lemma rule_instance_typed {K Sort V H F} (a : EggAlg.t K Sort V)
    (r : EggRule.t K Sort V H F) (sub : EggSubst.t K Sort V H) l u :
  EggRule.wf a r -> EggSubst.sub_typed a (EggRule.hole_sort r) sub ->
  EggSubst.instantiate sub (EggRule.lhs r) = Some l ->
  EggSubst.instantiate sub (EggRule.rhs r) = Some u ->
  EggTerm.typed a l /\ EggTerm.typed a u /\ EggTerm.sort_of l = EggTerm.sort_of u.
Proof.
  intros [_ [_ [Hlhs [Hrhs Hsort]]]] Hsub Hinstl Hinstu.
  destruct (EggSubst.instantiate_typed a (EggRule.hole_sort r) sub (EggRule.lhs r) Hlhs Hsub)
    as [l' [Hinstl' [Htypedl Hsortl]]].
  destruct (EggSubst.instantiate_typed a (EggRule.hole_sort r) sub (EggRule.rhs r) Hrhs Hsub)
    as [u' [Hinstu' [Htypedu Hsortu]]].
  rewrite Hinstl in Hinstl'; injection Hinstl' as Hleft; subst l'.
  rewrite Hinstu in Hinstu'; injection Hinstu' as Hright; subst u'.
  split; [exact Htypedl|split; [exact Htypedu|now rewrite Hsortl, Hsortu]].
Qed.

Local Lemma typed_app_inv {K Sort V} (a : EggAlg.t K Sort V) s op args :
  EggTerm.typed a (EggTerm.App s op args) ->
  Forall (EggTerm.typed a) args /\ EggAlg.op_shape a op (map EggTerm.sort_of args) s = true.
Proof.
  intros Htyped.
  inversion Htyped as [|s' op' args' Hargs Hshape]; subst.
  split; assumption.
Qed.

Local Lemma args_typed_agrees {K Sort V} (a : EggAlg.t K Sort V) ls rs :
  Forall2 (fun l r => EggTerm.sort_of l = EggTerm.sort_of r /\
    (EggTerm.typed a l <-> EggTerm.typed a r)) ls rs ->
  map EggTerm.sort_of ls = map EggTerm.sort_of rs /\
    (Forall (EggTerm.typed a) ls <-> Forall (EggTerm.typed a) rs).
Proof.
  intros Hargs.
  induction Hargs as [|l r ls rs [Hsort Htyped] Hrest [Hsorts Htypeds]].
  - split; [reflexivity|reflexivity].
  - split.
    + cbn; now rewrite Hsort, Hsorts.
    + rewrite !Forall_cons_iff; tauto.
Qed.

Local Lemma app_typed_agrees {K Sort V} (a : EggAlg.t K Sort V) s op ls rs :
  Forall2 (fun l r => EggTerm.sort_of l = EggTerm.sort_of r /\
    (EggTerm.typed a l <-> EggTerm.typed a r)) ls rs ->
  EggTerm.typed a (EggTerm.App s op ls) <-> EggTerm.typed a (EggTerm.App s op rs).
Proof.
  intros Hargs.
  destruct (args_typed_agrees a ls rs Hargs) as [Hsorts Htypeds].
  split; intro Htyped; apply EggTerm.typed_app.
  - apply Htypeds; exact (proj1 (typed_app_inv a s op ls Htyped)).
  - rewrite <- Hsorts; exact (proj2 (typed_app_inv a s op ls Htyped)).
  - apply Htypeds; exact (proj1 (typed_app_inv a s op rs Htyped)).
  - rewrite Hsorts; exact (proj2 (typed_app_inv a s op rs Htyped)).
Qed.

Local Lemma typed_agrees {K Sort V H F C} (a : EggAlg.t K Sort V)
    (adm : EggSem.t K V C -> Prop) (facts : EggFact.t F K Sort V C)
    (rules : list (EggRule.t K Sort V H F)) :
  Forall (EggRule.wf a) rules ->
  forall l r, rel a adm facts rules l r ->
    EggTerm.sort_of l = EggTerm.sort_of r /\ (EggTerm.typed a l <-> EggTerm.typed a r).
Proof.
  intros Hrules.
  apply (rel_ind_all a adm facts rules
    (fun l r => EggTerm.sort_of l = EggTerm.sort_of r /\
      (EggTerm.typed a l <-> EggTerm.typed a r))).
  - intro term; split; reflexivity.
  - intros l r Hequal [Hsort Htyped]; split; [symmetry; exact Hsort|tauto].
  - intros l m r Hlm [Hsortlm Htypedlm] Hmr [Hsortmr Htypedmr].
    split; [now transitivity (EggTerm.sort_of m)|tauto].
  - intros s op ls rs Hargs IHargs.
    split; [reflexivity|exact (app_typed_agrees a s op ls rs IHargs)].
  - intros rule sub phi l u Hin Hsub Hfacts Hguard Hlhs Hrhs.
    pose proof (proj1 (Forall_forall (EggRule.wf a) rules) Hrules rule Hin) as Hwf.
    destruct (rule_instance_typed a rule sub l u Hwf Hsub Hlhs Hrhs)
      as [Htypedl [Htypedu Hsort]].
    split; [exact Hsort|split; intro Htyped; assumption].
Qed.

(** Equality generated by well-formed rules preserves typing and the annotated result sort. *)
Theorem typed {K Sort V H F C} (a : EggAlg.t K Sort V)
    (adm : EggSem.t K V C -> Prop) (facts : EggFact.t F K Sort V C)
    (rules : list (EggRule.t K Sort V H F)) :
  Forall (EggRule.wf a) rules ->
  forall l r, EggTerm.typed a l -> rel a adm facts rules l r ->
    EggTerm.typed a r /\ EggTerm.sort_of l = EggTerm.sort_of r.
Proof.
  intros Hrules l r Htyped Hequal.
  destruct (typed_agrees a adm facts rules Hrules l r Hequal) as [Hsort Htypeds].
  split; [now apply Htypeds|exact Hsort].
Qed.

End EggEqual.
